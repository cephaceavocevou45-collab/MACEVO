export function getMacevoModelSpec(templateOrId = {}) {
  const id = typeof templateOrId === "string" ? templateOrId : templateOrId?.id;
  // Academic templates can use a public catalogue ID while their concrete
  // scenario profile is keyed by the structure ID (for example IMRaD).
  const profileId = typeof templateOrId === "object" && templateOrId?.structureId
    ? templateOrId.structureId
    : id;

  const additional = ADDITIONAL_MODEL_SCENARIOS[id] || ADDITIONAL_MODEL_SCENARIOS[profileId];
  if (additional) {
    const base = MACEVO_MODEL_SPECS["memoire-classique"];
    return {
      ...base,
      ...additional,
      // Do not carry the stock-management bibliography or figures into an
      // unrelated template. Model-specific references can be added when
      // verified for that discipline and country.
      references: additional.references || ADDITIONAL_MODEL_REFERENCES[id] || [],
      figureTitle: additional.figureTitle || `Dimensions d’analyse — ${additional.domain}`,
      tableTitle: additional.tableTitle || `Synthèse des résultats — ${additional.domain}`,
      equation: additional.equation || ADDITIONAL_MODEL_EQUATIONS[id] || "",
    };
  }
  return MACEVO_MODEL_SPECS[id] || MACEVO_MODEL_SPECS[profileId] || createNeutralModelSpec(templateOrId);
}
